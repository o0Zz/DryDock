/**
 * Copy text to the clipboard. `navigator.clipboard` only exists on HTTPS and localhost,
 * and DryDock often runs on plain HTTP on the LAN: there the old `execCommand` copy of a
 * hidden textarea still works.
 */
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Refused (no focus, no permission): try the old way.
    }
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  try {
    return document.execCommand("copy");
  } finally {
    area.remove();
  }
}
